#!/usr/bin/env python3

import argparse
import subprocess
import sys
from pathlib import Path

MARKER = "<!-- newproj:student-scaffold -->"
DIRECTORIES = [
    "data/raw",
    "data/processed",
    "docs/plans",
    "docs/notes",
    "src",
    "output/figures",
    "output/tables",
    "report",
    "slides",
    "tests",
    "temp",
    ".state",
    ".logs",
]
AGENTS_TEMPLATE = """<!-- newproj:student-scaffold -->
# Project: {title}

## Folder structure

- `data/raw/`: Original input data; keep these files unchanged.
- `data/processed/`: Data generated by project scripts.
- `docs/plans/`: Plans created during project work.
- `docs/notes/`: Notes created during project work.
- `src/`: Reusable project scripts.
- `output/figures/`: Generated figures.
- `output/tables/`: Generated tables.
- `report/`: Analyst-authored reports.
- `slides/`: Team presentations and HTML briefings.
- `tests/`: Code and reproducibility checks.
- `temp/`: Disposable files.
- `.state/`: Runtime state.
- `.logs/`: Execution logs.
"""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create the standard project folder structure."
    )
    parser.add_argument("project_name", nargs="?", help="New project directory name")
    parser.add_argument("--path", type=Path, help="Specific directory to scaffold")
    parser.add_argument("--title", help="Project title; defaults to the directory name")
    parser.add_argument("--dry-run", action="store_true", help="Preview without writing")
    parser.add_argument(
        "--git", action="store_true", help="Initialize Git on main without committing"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Scaffold a nonempty directory without overwriting files",
    )
    args = parser.parse_args()
    if args.project_name and args.path:
        parser.error("use either project_name or --path, not both")
    if not args.project_name and not args.path:
        parser.error("provide project_name or --path")
    return args


def is_existing_scaffold(path: Path) -> bool:
    agents = path / "AGENTS.md"
    try:
        return agents.is_file() and MARKER in agents.read_text(encoding="utf-8")
    except OSError:
        return False


def write_if_missing(path: Path, content: str, dry_run: bool) -> None:
    if path.exists():
        return
    if dry_run:
        print(f"Would create {path}")
        return
    path.write_text(content, encoding="utf-8")
    print(f"Created {path}")


def main() -> int:
    args = parse_args()
    project = args.path.expanduser() if args.path else Path.cwd() / args.project_name
    project = project.resolve()
    title = args.title or project.name
    dry_run = args.dry_run

    if project.exists() and not project.is_dir():
        print(f"Refusing to scaffold over a file: {project}", file=sys.stderr)
        return 1
    if (
        project.is_dir()
        and any(project.iterdir())
        and not args.force
        and not is_existing_scaffold(project)
    ):
        print(
            f"Refusing to scaffold unexpected nonempty directory: {project}\n"
            "Use --force to add missing scaffold items without overwriting files.",
            file=sys.stderr,
        )
        return 1

    if dry_run:
        print(f"Previewing project scaffold at {project}")
    elif not project.exists():
        project.mkdir(parents=True)
        print(f"Created {project}")

    for relative in DIRECTORIES:
        directory = project / relative
        if dry_run:
            if not directory.exists():
                print(f"Would create {directory}")
        else:
            directory.mkdir(parents=True, exist_ok=True)
        write_if_missing(directory / ".gitkeep", "", dry_run)

    write_if_missing(project / "AGENTS.md", AGENTS_TEMPLATE.format(title=title), dry_run)
    template = Path(__file__).with_name("gitignore_template.txt").read_text(encoding="utf-8")
    write_if_missing(project / ".gitignore", template, dry_run)

    if args.git and not (project / ".git").exists():
        if dry_run:
            print(f"Would initialize Git on main in {project}")
        else:
            subprocess.run(
                ["git", "init", "-b", "main"],
                cwd=project,
                check=True,
                capture_output=True,
                text=True,
            )
            print(f"Initialized Git on main in {project}; no files staged or committed")

    print(f"Project scaffold ready: {project}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
